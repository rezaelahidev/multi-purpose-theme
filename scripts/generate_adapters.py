#!/usr/bin/env python3
"""Deterministic provider adapter generator."""
import argparse, hashlib, json, re, sys
from pathlib import Path
import yaml
ROOT=Path(__file__).resolve().parents[1]
MANIFEST=ROOT/".ai/adapters/generated-manifest.json"
MARKER="<!-- GENERATED BY scripts/generate_adapters.py; DO NOT EDIT. -->"
PROVIDERS={"cursor","claude-code","codex"}
CAPS={"native","shared","instruction-only","unsupported","unverified"}

def read_yaml(path):
    with path.open(encoding="utf-8") as stream: data=yaml.safe_load(stream)
    if not isinstance(data,dict): raise ValueError(f"{path}: expected YAML object")
    return data

def safe_path(relative):
    if not isinstance(relative, str) or not relative: raise ValueError("Generated path must be a non-empty string")
    p=Path(relative)
    if p.is_absolute() or ".." in p.parts or not p.parts or p.parts[0] not in {".cursor", ".claude", ".codex"}:
        raise ValueError("Unsafe generated path: "+relative)
    allowed = (
        (p.parts == (".cursor", "rules", "ai-core.mdc")) or
        (p.parts == (".cursor", "capability-report.md")) or
        (p.parts == (".claude", "capability-report.md")) or
        (p.parts == (".codex", "capability-report.md")) or
        (len(p.parts) == 3 and p.parts[0] == ".cursor" and p.parts[1] == "agents" and p.suffix == ".md") or
        (len(p.parts) == 3 and p.parts[0] == ".claude" and p.parts[1] == "agents" and p.suffix == ".md")
    )
    if not allowed: raise ValueError("Path is not an approved generated output: "+relative)
    candidate = ROOT / p
    current = candidate
    while current != ROOT:
        if current.is_symlink(): raise ValueError("Refusing to follow symlink in generated path: "+relative)
        current = current.parent
    resolved = candidate.resolve()
    if ROOT.resolve() not in resolved.parents: raise ValueError("Path escapes repository: "+relative)
    return resolved

def frontmatter(values):
    return "---\n"+"\n".join(f"{k}: {json.dumps(v,ensure_ascii=False)}" for k,v in values.items())+"\n---"

def body(a):
    lines=[f"# {a['name']}","","Canonical agent: "+a["id"]+"@"+a["version"],"Mission: "+a["mission"],"",
    "## Before acting","- Read AGENTS.md, project status, and the assigned task.",
    "- Read the canonical agent contract in .ai/agents/.",
    "- Confirm ownership, dependencies, approval status, and file scope.",
    "- Read only relevant governance documents and skills.","","## Responsibilities"]
    lines += ["- "+x for x in a.get("responsibilities",[])]
    lines += ["","## Required inputs"]+["- "+x for x in a.get("inputs",{}).get("required",[])]
    lines += ["","## Required outputs"]+["- "+x for x in a.get("outputs",{}).get("required",[])]
    lines += ["","## Skills"]+["- .agents/skills/"+x+"/SKILL.md" for x in a.get("skills",[])]
    lines += ["","## Constraints"]+["- "+x for x in a.get("constraints",[])]
    lines += ["- Never self-approve a human gate.","- Prompt instructions are not equivalent to runtime-enforced permissions.","- Do not claim unverified capabilities or test results.","","## Quality criteria"]
    lines += ["- "+x for x in a.get("quality",{}).get("criteria",[])]
    lines += ["","## Handoff","Report artifacts, acceptance evidence, unresolved questions, risks, and next owner."]
    return "\n".join(lines)+"\n"

def render(profiles,agents):
    out={}
    for provider in sorted(profiles):
        if provider not in PROVIDERS: raise ValueError("Unknown provider: "+provider)
        profile=profiles[provider]; caps=profile.get("capabilities",{})
        if any(v not in CAPS for v in caps.values()): raise ValueError("Invalid capability in "+provider)
        if provider=="cursor":
            out[".cursor/rules/ai-core.mdc"]=MARKER+"\n---\ndescription: Shared AI-native project governance\nalwaysApply: true\n---\nFollow AGENTS.md. Canonical contracts, workflows, state, and skills live in .ai/ and .agents/skills/. Do not edit generated files. Respect human approval gates and task file scope.\n"
            if caps.get("subagents") == "native":
                for a in agents:
                    out[".cursor/agents/"+a["id"]+".md"]=MARKER+"\n"+frontmatter({"name":a["id"],"description":a["mission"]})+"\n\n"+body(a)
            else:
                docs="\n".join("- "+u for u in profile.get("documentation",[]))
                out[".cursor/capability-report.md"]=MARKER+"\n# Cursor capability report\n\nSubagent generation is disabled until this capability is verified as native.\n\n## Capability mapping\n"+"\n".join("- "+k+": "+v for k,v in sorted(caps.items()))+"\n\n## Official references\n"+docs+"\n"
        elif provider=="claude-code":
            if caps.get("subagents") == "native":
                for a in agents:
                    out[".claude/agents/"+a["id"]+".md"]=MARKER+"\n"+frontmatter({"name":a["id"],"description":a["mission"]})+"\n\n"+body(a)
            else:
                docs="\n".join("- "+u for u in profile.get("documentation",[]))
                out[".claude/capability-report.md"]=MARKER+"\n# Claude Code capability report\n\nSubagent generation is disabled until this capability is verified as native.\n\n## Capability mapping\n"+"\n".join("- "+k+": "+v for k,v in sorted(caps.items()))+"\n\n## Official references\n"+docs+"\n"
        else:
            lines=["- **"+k.replace("_"," ")+"**: "+v for k,v in sorted(caps.items())]
            docs="\n".join("- "+u for u in profile.get("documentation",[]))
            out[".codex/capability-report.md"]=MARKER+"\n# Codex capability report\n\n## Capability mapping\n"+"\n".join(lines)+"\n\n## Official references\n"+docs+"\n"
    return out

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write",action="store_true"); group.add_argument("--check",action="store_true")
    args=parser.parse_args()
    try:
        cfg=read_yaml(ROOT/".ai/adapters/providers.yaml")
        if cfg.get("version")!="1.0" or set(cfg.get("providers",{}))!=PROVIDERS: raise ValueError("Invalid provider profile version or provider set")
        for provider_id, profile in cfg["providers"].items():
            status=profile.get("verification_status")
            verified_on=profile.get("last_verified")
            if status not in {"pending","verified"}: raise ValueError("Invalid verification status for "+provider_id)
            if status=="verified" and (not isinstance(verified_on,str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}",verified_on)):
                raise ValueError("Verified provider profile requires ISO last_verified date: "+provider_id)
            if status=="pending" and verified_on is not None: raise ValueError("Pending provider profile must not have last_verified date: "+provider_id)
            if status!="verified" and "native" in profile.get("capabilities",{}).values():
                raise ValueError("Native capability requires verified provider profile: "+provider_id)
        agents=[]; ids=set()
        for p in sorted((ROOT/".ai/agents").glob("*.yaml")):
            a=read_yaml(p).get("agent")
            if not isinstance(a,dict) or not re.fullmatch(r"[a-z0-9][a-z0-9-]*",str(a.get("id",""))): raise ValueError("Invalid agent in "+str(p))
            if a["id"] in ids: raise ValueError("Duplicate agent ID: "+a["id"])
            ids.add(a["id"]); agents.append(a)
        if not agents: raise ValueError("No canonical agents found")
        desired=render(cfg["providers"],agents)
        old=json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else {"version":1,"files":{}}
        if old.get("version")!=1 or not isinstance(old.get("files"),dict): raise ValueError("Invalid manifest")
        hashes={p:hashlib.sha256(c.encode()).hexdigest() for p,c in sorted(desired.items())}
        problems=[]
        for rel,content in desired.items():
            path=safe_path(rel)
            if path.exists():
                current=path.read_text(encoding="utf-8")
                if current!=content and MARKER not in current: raise ValueError("Refusing to overwrite non-generated file: "+rel)
                if current!=content:
                    problems.append("modified: "+rel)
                    if args.write: path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content,encoding="utf-8")
            else:
                problems.append("missing: "+rel)
                if args.write: path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content,encoding="utf-8")
        for rel in sorted(set(old["files"])-set(desired)):
            path=safe_path(rel)
            if path.exists():
                if MARKER not in path.read_text(encoding="utf-8"): raise ValueError("Refusing to remove unmarked file: "+rel)
                problems.append("stale: "+rel)
                if args.write: path.unlink()
        if args.write:
            MANIFEST.parent.mkdir(parents=True,exist_ok=True)
            MANIFEST.write_text(json.dumps({"version":1,"files":hashes},indent=2)+"\n",encoding="utf-8")
            print("Generated "+str(len(desired))+" adapter files."); return 0
        if hashes!=old.get("files",{}): problems.append("generated manifest is missing or stale")
        if problems:
            print("Drift detected:\n"+"\n".join("- "+p for p in problems)); return 1
        print("PASS: "+str(len(desired))+" generated files synchronized."); return 0
    except (OSError,ValueError,KeyError,TypeError,yaml.YAMLError,json.JSONDecodeError) as exc:
        print("ERROR: "+str(exc),file=sys.stderr); return 2

if __name__=="__main__": sys.exit(main())
